// data/missing-coordinates-report.md, as a pure function of the event files (no network, no clock), so that
// re-running it on unchanged data gives an identical file and CI can tell when the committed copy is stale
// (scripts/build-missing-coordinates-report.js --check).
//
// Sitelink counts are the stored ones: `sitelinks_current` (Wikidata sitelinks, refreshed monthly by
// scripts/refresh-sitelinks.js), else the discovery count `sitelinks`. Before 2026-10-14 the report was written
// only by enrich-candidates.js, which fetched every curated event's count live (one request per event).
import { compareQids } from "./wdqs.js";
import { INCLUSION_MIN_SITELINKS } from "./event-classes.js";

const mdEscape = (s) => String(s ?? "").replace(/\|/g, "\\|");
const wdLink = (q) => (q ? `[${q}](https://www.wikidata.org/wiki/${q})` : "-");
const sitelinksOf = (e) => (typeof e.sitelinks_current === "number" ? e.sitelinks_current : typeof e.sitelinks === "number" ? e.sitelinks : null);
const fallbackLabel = (e) =>
  e.coordinates ? `pin at ${String(e.coordinate_source).replace("country-fallback:", "")} capital (approximate)` : "no location";
const bySitelinks = (a, b) => (sitelinksOf(b) ?? -1) - (sitelinksOf(a) ?? -1) || compareQids(a.wikidata_qid, b.wikidata_qid);

// Curated events without a precise location: no coordinates, or a capital-fallback pin.
export const lacksPreciseLocation = (e) => !e.coordinates || String(e.coordinate_source ?? "").startsWith("country-fallback");

// The newest retrieval date in the inputs (YYYY-MM-DD), so the header is dated by the data.
export function reportDataAsOf(curated, proposed) {
  return (
    [...curated.map((e) => e.extract_retrieved_at), ...proposed.map((e) => e.retrieved_at ?? e.extract_retrieved_at)]
      .filter((d) => typeof d === "string")
      .map((d) => d.slice(0, 10))
      .sort()
      .at(-1) ?? null
  );
}

// curated: data/events.json; proposed: data/events.proposed.json. Section 2 lists the proposed events without a
// location that are not curated yet (curated ones are already in section 1).
export function renderMissingReport({ curated, proposed }) {
  const curatedQids = new Set(curated.map((e) => e.wikidata_qid).filter(Boolean));
  const curatedIds = new Set(curated.map((e) => e.id));
  const rowsCurated = curated.filter(lacksPreciseLocation).sort(bySitelinks);
  const rowsProposed = proposed
    .filter((e) => e.location_quality === "none" && !curatedQids.has(e.wikidata_qid) && !curatedIds.has(e.id))
    .sort(bySitelinks);
  const table = (rows) =>
    [
      "| # | Event | Date | Sitelinks | Current fallback | Wikipedia | Wikidata |",
      "|---|---|---|---|---|---|---|",
      ...rows.map(
        (r, i) =>
          `| ${i + 1} | ${mdEscape(r.title)} | ${r.date_start ?? ""} | ${sitelinksOf(r) ?? "?"} | ${fallbackLabel(r)} | ${
            r.wikipedia_url ? `[article](${r.wikipedia_url})` : "-"
          } | ${wdLink(r.wikidata_qid)} |`
      ),
    ].join("\n");

  const md = `# Events without a precise location

Generated by \`node scripts/build-missing-coordinates-report.js\` from \`data/events.json\` and \`data/events.proposed.json\`
(data retrieved up to ${reportDataAsOf(curated, proposed) ?? "(unknown)"}). Sitelinks are the stored counts (\`sitelinks_current\`, refreshed monthly).

These events have **no coordinates on Wikipedia or Wikidata**, so middleeast.events can only pin them at a
country-capital fallback (curated events only, labelled "approximate location") or not at all. Proposed events in
the second table are in \`data/events.proposed.json\` with \`location_quality: "none"\` and \`coordinates: null\`
(listed and searchable once merged, but no map marker; a location is never invented).

The fix belongs upstream: if you know the real location of an event, you can add a coordinate location
(property **P625**) to its Wikidata item (linked below) with a reference. This pipeline never invents
coordinates and never edits Wikipedia or Wikidata. Rows are sorted by significance = number of Wikimedia
sitelinks (the same objective signal used for inclusion; it is a proxy, see docs/DATA_POLICY.md).

## 1. Curated events (data/events.json) lacking a precise location - ${rowsCurated.length}

${table(rowsCurated)}

## 2. Proposed events not yet curated (sitelinks >= ${INCLUSION_MIN_SITELINKS}) with location_quality "none" (no real location) - ${rowsProposed.length}

${table(rowsProposed)}
`;
  return { md, curated: rowsCurated.length, proposed: rowsProposed.length };
}
