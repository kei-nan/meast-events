// Redirects for renamed event ids: data/event-redirects.json (optional, owned by
// whoever curates the data) -> dist/_redirects, which the static-assets Worker
// applies before serving any file (developers.cloudflare.com/workers/static-assets/redirects/:
// "Redirects are always followed, regardless of whether or not an asset matches").
//
// The data file maps an old id to the id that replaced it:
//   { "treaty-of-s-vres": "treaty-of-sevres" }
// Each entry becomes "/event/<old> /event/<new> 301", so a shared link to the old
// address lands on the event's new page. Nothing here renames an id: an entry is
// only valid once the new id is in the data and the old one is not.
//
// build-event-pages.mjs writes dist/_redirects with redirectsFile(); check-dist.mjs
// re-reads it with checkRedirectsText(). Tested in redirects.test.mjs.
import { eventPath, isValidEventId } from "../src/lib/urlState.js";

// The host's limit for static redirects (developers.cloudflare.com/workers/platform/limits/).
export const MAX_STATIC_REDIRECTS = 2000;

/**
 * Problems with a redirect map ({old id: new id}) against the current event ids
 * (a Set): each old id must be a valid id that is no longer an event (a redirect
 * from a live page would hide it), each new id a current event (no redirect to a
 * 404, no chains). Returns a list of messages, empty when the map is good.
 */
export function redirectProblems(map, ids) {
  if (!map || typeof map !== "object" || Array.isArray(map)) return ["event-redirects.json is not an object of {old id: new id}"];
  const problems = [];
  const entries = Object.entries(map);
  for (const [from, to] of entries) {
    if (!isValidEventId(from)) problems.push(`redirect from ${JSON.stringify(from)}: not a valid event id`);
    else if (ids.has(from)) problems.push(`redirect from ${from}: it is still an event, so its page would be redirected away`);
    if (typeof to !== "string" || !isValidEventId(to)) problems.push(`redirect ${from} -> ${JSON.stringify(to)}: not a valid event id`);
    else if (!ids.has(to)) problems.push(`redirect ${from} -> ${to}: ${to} is not an event${Object.hasOwn(map, to) ? " (a chain: point to the final id)" : ""}`);
  }
  if (entries.length > MAX_STATIC_REDIRECTS) problems.push(`${entries.length} redirects; the host allows ${MAX_STATIC_REDIRECTS}`);
  return problems;
}

/** dist/_redirects for a valid map: one 301 per old id, sorted. */
export function redirectsFile(map) {
  const lines = Object.entries(map)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([from, to]) => `${eventPath(from)} ${eventPath(to)} 301`);
  return `# Generated by scripts/build-event-pages.mjs from data/event-redirects.json; do not edit.\n${lines.join("\n")}\n`;
}

/**
 * Problems with a built dist/_redirects (its text) against the current event ids:
 * every line must be "/event/<old> /event/<new> 301" as redirectsFile writes it,
 * with the same rules as redirectProblems.
 */
export function checkRedirectsText(text, ids) {
  const map = {};
  const problems = [];
  const lines = text.split(/\r?\n/).filter((l) => l.trim() && !l.startsWith("#"));
  for (const line of lines) {
    const m = /^\/event\/([^/\s]+) \/event\/([^/\s]+) 301$/.exec(line);
    if (!m) {
      problems.push(`_redirects: unexpected line ${JSON.stringify(line)}`);
      continue;
    }
    const [from, to] = [decodeURIComponent(m[1]), decodeURIComponent(m[2])];
    if (Object.hasOwn(map, from)) problems.push(`_redirects: ${from} is redirected twice`);
    map[from] = to;
  }
  return [...problems, ...redirectProblems(map, ids).map((p) => `_redirects: ${p}`)];
}
