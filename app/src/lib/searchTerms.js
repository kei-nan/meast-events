// Which words of a query the full-text index (Pagefind) really holds.
//
// Pagefind matches each query word, stemmed, as a prefix of the words it
// indexed ("suez" finds "suez" and "suezkan"). When NO indexed word starts with
// it, Pagefind does not answer "nothing": it falls back to the longest indexed
// word the query word starts with ("aaaaaaaa" -> "a", 714 events;
// "jerusalemxyz" -> "jerusalem"), and a word with not even that is dropped from
// a many-word query ("suez qqqqqqqq" -> the "suez" events). This is documented
// (CHANGELOG 1.0.0: "returns results for a prefix of the search word if there
// would otherwise be zero results"), lives in pagefind_web/src/search.rs
// (find_word_extensions, search_term) and no option turns it off.
//
// So lib/textSearch.js asks the index's own word list (words.json, written by
// scripts/build-search-index.mjs from the index chunks) whether every query
// word has a genuine match, the same test Pagefind applies before its
// fallback, and answers no events when one has not. For that the query is cut
// into words, folded and stemmed exactly as Pagefind does it:
//   - queryTerms: pagefind.js search() (lowercase, drop punctuation, NFD
//     without combining marks, split on spaces);
//   - stemEnglish: the Snowball 3.0.0 English stemmer its WebAssembly runs
//     (pagefind_stem; the index is built with forceLanguage "en").
//     scripts/build-search-index.mjs checks both against the index at every build.

// Symbols ($ + ~ ₪ ...) and bidi marks are never part of an indexed word (the
// indexer drops them: "US$500" is indexed as "us500", "8000+" as "8000"), but
// pagefind.js keeps them in the query, where they could only ever match through
// the fallback. So they are removed from the query before it is searched.
const NOT_INDEXED = /[\p{S}\u200e\u200f\u202a-\u202e\u2066-\u2069]/gu;
export const pagefindQuery = (q) => String(q ?? "").replace(NOT_INDEXED, "");

// Punctuation pagefind.js removes from the query (its regex, precedence and all).
const PF_PUNCT = /^\p{Pd}|\p{Pe}|\p{Pf}|\p{Pi}|\p{Po}|\p{Ps}$/u;

// The words Pagefind searches for q, before stemming.
export function queryTerms(q) {
  const s = String(q ?? "");
  let out = "";
  const graphemes =
    typeof Intl !== "undefined" && typeof Intl.Segmenter === "function"
      ? Array.from(new Intl.Segmenter("en", { granularity: "grapheme" }).segment(s), (g) => g.segment)
      : Array.from(s);
  for (const g of graphemes) if (!PF_PUNCT.test(g)) out += g.toLocaleLowerCase();
  out = out.replace(/\s{2,}/g, " ").trim().normalize("NFD").replace(/\p{M}/gu, "");
  return out ? out.split(" ") : [];
}

// ---- Snowball English stemmer, as generated by Snowball 3.0.0
// (https://github.com/snowballstem/snowball/blob/master/algorithms/english.sbl).

const isV = (c) => c === "a" || c === "e" || c === "i" || c === "o" || c === "u" || c === "y";

const EXCEPTION1 = {
  skis: "ski",
  skies: "sky",
  idly: "idl",
  gently: "gentl",
  ugly: "ugli",
  early: "earli",
  only: "onli",
  singly: "singl",
  sky: "sky",
  news: "news",
  howe: "howe",
  atlas: "atlas",
  cosmos: "cosmos",
  bias: "bias",
  andes: "andes",
};
const R1_PREFIXES = ["arsen", "commun", "emerg", "gener", "inter", "later", "organ", "past", "univers"];

// [suffix, replacement], longest first (Snowball's `among` takes the longest).
const STEP2 = [
  ["ization", "ize"],
  ["ational", "ate"],
  ["fulness", "ful"],
  ["ousness", "ous"],
  ["iveness", "ive"],
  ["tional", "tion"],
  ["biliti", "ble"],
  ["lessli", "less"],
  ["entli", "ent"],
  ["ation", "ate"],
  ["alism", "al"],
  ["aliti", "al"],
  ["ousli", "ous"],
  ["iviti", "ive"],
  ["fulli", "ful"],
  ["ogist", "og"],
  ["enci", "ence"],
  ["anci", "ance"],
  ["abli", "able"],
  ["izer", "ize"],
  ["ator", "ate"],
  ["alli", "al"],
  ["bli", "ble"],
  ["ogi", "og"], // only after l
  ["li", ""], // only after a valid li-ending
];
const STEP3 = [
  ["ational", "ate"],
  ["tional", "tion"],
  ["alize", "al"],
  ["icate", "ic"],
  ["iciti", "ic"],
  ["ative", ""], // only in R2
  ["ical", "ic"],
  ["ness", ""],
  ["ful", ""],
];
const STEP4 = ["ement", "ance", "ence", "able", "ible", "ment", "ant", "ent", "ism", "ate", "iti", "ous", "ive", "ize", "ion", "al", "er", "ic"];

const endsWithAny = (w, suffixes) => suffixes.find((s) => w.endsWith(Array.isArray(s) ? s[0] : s));

export function stemEnglish(word) {
  let w = String(word);
  if (Object.hasOwn(EXCEPTION1, w)) return EXCEPTION1[w];
  if (Array.from(w).length < 3) return w;

  // Prelude: drop an initial apostrophe; y at the start or after a vowel -> Y.
  if (w[0] === "'") w = w.slice(1);
  const chars = Array.from(w);
  if (chars[0] === "y") chars[0] = "Y";
  for (let i = 1; i < chars.length; i++) if (chars[i] === "y" && isV(chars[i - 1])) chars[i] = "Y";
  w = chars.join("");

  // Regions R1/R2 as offsets into w (from here on w only changes at its end).
  const afterVnv = (from) => {
    for (let i = from; i < w.length - 1; i++) if (isV(w[i]) && !isV(w[i + 1])) return i + 2;
    return w.length;
  };
  const prefix = R1_PREFIXES.find((p) => w.startsWith(p));
  const p1 = prefix ? prefix.length : afterVnv(0);
  const p2 = afterVnv(p1);
  const inR1 = (suffixLen) => w.length - suffixLen >= p1;
  const inR2 = (suffixLen) => w.length - suffixLen >= p2;
  // s ends in a short syllable.
  const shortV = (s) => {
    const n = s.length;
    if (n >= 3 && !isV(s[n - 3]) && isV(s[n - 2]) && !isV(s[n - 1]) && !"wxY".includes(s[n - 1])) return true;
    if (n === 2 && isV(s[0]) && !isV(s[1])) return true;
    return s.endsWith("past");
  };
  const hasVowel = (s) => Array.from(s).some(isV);

  // Step 1a.
  const apos = endsWithAny(w, ["'s'", "'s", "'"]);
  if (apos) w = w.slice(0, -apos.length);
  if (w.endsWith("sses")) w = w.slice(0, -2);
  else if (w.endsWith("ied") || w.endsWith("ies")) w = w.length > 4 ? w.slice(0, -2) : w.slice(0, -1);
  else if (w.endsWith("us") || w.endsWith("ss")) {
    // unchanged
  } else if (w.endsWith("s") && hasVowel(w.slice(0, -2))) w = w.slice(0, -1);

  // Step 1b.
  const s1b = endsWithAny(w, ["eedly", "ingly", "edly", "eed", "ing", "ed"]);
  let general = Boolean(s1b);
  if (s1b === "eed" || s1b === "eedly") {
    general = false;
    const rest = w.slice(0, -s1b.length);
    if (inR1(s1b.length) && !["proc", "exc", "succ"].includes(rest)) w = rest + "ee";
  } else if (s1b === "ing") {
    const rest = w.slice(0, -3);
    if (rest.length === 2 && rest[1] === "y" && !isV(rest[0])) {
      w = rest[0] + "ie"; // dying -> die
      general = false;
    } else if (["inn", "out", "cann", "herr", "earr", "even"].includes(rest)) general = false;
  }
  if (general && hasVowel(w.slice(0, -s1b.length))) {
    w = w.slice(0, -s1b.length);
    if (w.endsWith("at") || w.endsWith("bl") || w.endsWith("iz")) w += "e";
    else if (/(bb|dd|ff|gg|mm|nn|pp|rr|tt)$/.test(w)) {
      if (!(w.length === 3 && "aeo".includes(w[0]))) w = w.slice(0, -1);
    } else if (w.length === p1 && shortV(w)) w += "e";
  }

  // Step 1c.
  if (w.length > 2 && (w.endsWith("y") || w.endsWith("Y")) && !isV(w[w.length - 2])) w = w.slice(0, -1) + "i";

  // Step 2.
  const s2 = endsWithAny(w, STEP2);
  if (s2 && inR1(s2[0].length)) {
    const stem = w.slice(0, -s2[0].length);
    if (s2[0] === "ogi") {
      if (stem.endsWith("l")) w = stem + "og";
    } else if (s2[0] === "li") {
      if (/[cdeghkmnrt]$/.test(stem)) w = stem;
    } else w = stem + s2[1];
  }

  // Step 3.
  const s3 = endsWithAny(w, STEP3);
  if (s3 && inR1(s3[0].length) && (s3[0] !== "ative" || inR2(5))) w = w.slice(0, -s3[0].length) + s3[1];

  // Step 4.
  const s4 = endsWithAny(w, STEP4);
  if (s4 && inR2(s4.length)) {
    if (s4 !== "ion") w = w.slice(0, -s4.length);
    else if (/[st]ion$/.test(w)) w = w.slice(0, -3);
  }

  // Step 5.
  if (w.endsWith("e")) {
    if (inR2(1) || (inR1(1) && !shortV(w.slice(0, -1)))) w = w.slice(0, -1);
  } else if (w.endsWith("ll") && inR2(1)) w = w.slice(0, -1);

  return w.replace(/Y/g, "y");
}

// ---- The index's word list

// Does `words` (sorted by JS's default sort, as build-search-index.mjs writes
// words.json) hold a word starting with prefix?
export function hasWordWithPrefix(words, prefix) {
  let lo = 0;
  let hi = words.length;
  while (lo < hi) {
    const mid = (lo + hi) >> 1;
    if (words[mid] < prefix) lo = mid + 1;
    else hi = mid;
  }
  return lo < words.length && words[lo].startsWith(prefix);
}

// Does Pagefind match every word of q (a pagefindQuery) itself (stemmed, as a
// prefix of an indexed word), not through its fallback?
export function everyTermIndexed(q, words) {
  const terms = queryTerms(q);
  return terms.length > 0 && terms.every((t) => hasWordWithPrefix(words, stemEnglish(t)));
}
